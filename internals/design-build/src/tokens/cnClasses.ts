import type { TokenModel } from '@lumen/design-sources';
import type { Target } from '../core/target.js';
import { breakpointLayers, layerTokens, orderedBreakpoints } from './modes.js';
import { outputSegment, typographyStyles } from './naming.js';

/**
 * The class steps `cn` merges as one typography group (`heading-0`,
 * `heading-0-semi-bold`…), from the same styles the Tailwind classes are
 * built from, so a new text style needs no edit in `cn.ts`.
 */
export const cnClassesTarget = (outDir: string): Target<TokenModel> => ({
  name: 'cn-classes',
  outDir,
  emit: (model) => {
    const [base] = breakpointLayers(model, orderedBreakpoints(model));
    const steps: Record<string, string[]> = {};
    for (const { group, step, weights } of typographyStyles(
      layerTokens(model, base),
    )) {
      const name = outputSegment(group);
      steps[name] ??= [];
      for (const { semiBold } of weights) {
        steps[name].push(
          semiBold ? `${outputSegment(step)}-semi-bold` : outputSegment(step),
        );
      }
    }

    return [
      {
        path: 'typography.ts',
        contents: `/**
 * Do not edit directly, this file was auto-generated by design-build.
 */

/** Text style → the class steps it comes in (\`heading\` → \`0\`, \`0-semi-bold\`…). */
export const typographyClassSteps: Record<string, string[]> = ${JSON.stringify(steps)};
`,
      },
    ];
  },
});
