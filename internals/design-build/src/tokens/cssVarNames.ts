import type { TokenModel } from '@lumen/design-sources';
import type { Target } from '../core/target.js';
import { cssLayers } from './cssLayers.js';
import { orderedBreakpoints } from './selections.js';

/** The raw light and dark palettes: a component reads the semantic layer. */
const PALETTE = /^--color-(light|dark)-/;

/**
 * The `CSSVarName` type `cssVar` checks names against: every primitive,
 * typography and semantic variable, without the raw palettes.
 */
export const cssVarNamesTarget = (outDir: string): Target<TokenModel> => ({
  name: 'css-var-names',
  outDir,
  emit: (model) => {
    const layers = cssLayers(model, orderedBreakpoints(model));
    const names = [
      ...new Set(
        [
          layers.primitives,
          ...layers.breakpoints.map(({ declarations }) => declarations),
          ...layers.themes.map(({ declarations }) => declarations),
        ].flatMap(Object.keys),
      ),
    ]
      .filter((name) => !PALETTE.test(name))
      .sort();

    return [
      {
        path: 'cssVarName.ts',
        contents: `/**
 * Do not edit directly, this file was auto-generated by design-build.
 */

/** Every Lumen CSS variable \`cssVar\` accepts. */
export type CSSVarName =
${names.map((name) => `  | '${name}'`).join('\n')};
`,
      },
    ];
  },
});
